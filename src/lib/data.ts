// Deterministic 14-day series so server and client render the same numbers.
function series(seed: number, base: number): number[] {
  return Array.from({ length: 14 }, (_, i) => {
    const wave = Math.sin((i + seed) * 1.3) * 0.35 + Math.cos((i * seed) % 7) * 0.15;
    return Math.max(1, Math.round(base * (1 + wave) + i * (base / 40)));
  });
}

function stats(seed: number, base: number) {
  const viewsByDay = series(seed, base);
  const recent = viewsByDay.reduce((a, b) => a + b, 0);
  const views = recent * 2 + seed * 7;
  return {
    views,
    phoneReveals: Math.round(views * 0.18),
    callClicks: Math.round(views * 0.09),
    whatsappClicks: Math.round(views * 0.06),
    viewsByDay,
  };
}

